export function createTranslator(locale = 'zh-CN') {
  const english = /^en(?:-|$)/i.test(locale);
  return (source, values = {}) => {
    const message = english ? (englishMessages[source] ?? source) : source;
    return String(message ?? '').replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
  };
}
export function formatStamp(value, locale) {
  return new Date(value).toLocaleString(locale, {month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hour12: false});
}
export function formatDuration(job, locale) {
  const seconds = Math.max(0, Math.round((new Date(job.updatedAt) - new Date(job.createdAt)) / 1000));
  const t = createTranslator(locale), number = value => new Intl.NumberFormat(locale).format(value);
  return seconds < 60 ? t('{seconds} 秒', {seconds: number(seconds)}) : t('{minutes} 分 {seconds} 秒', {minutes: number(Math.floor(seconds / 60)), seconds: number(seconds % 60)});
}

export function knownMessage(message, fallback) {
  return Object.hasOwn(englishMessages, message) ? message : fallback;
}
